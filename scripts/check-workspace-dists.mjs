#!/usr/bin/env node
/**
 * Fail fast when a workspace package's `dist/` is older than its `src/`.
 *
 * Apps resolve `@plane/*` imports to the built `dist/` output, not to source.
 * A direct `pnpm --filter=<app> build` bypasses turbo's `dependsOn: ["^build"]`
 * ordering, so it can silently bundle stale package code (e.g. a settings
 * sidebar item that exists in source but is missing from the built bundle).
 *
 * Wired as `prebuild` in apps that ship workspace code (web, live) so the
 * failure happens before the bundle is produced, with an actionable message.
 *
 * Usage: node scripts/check-workspace-dists.mjs
 * Exit 0 when every dist is fresh, exit 1 listing stale packages otherwise.
 */

import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const REPO_ROOT = join(new URL(".", import.meta.url).pathname, "..");
const PACKAGES_DIR = join(REPO_ROOT, "packages");

const SKIP_DIRS = new Set(["node_modules", ".turbo", ".git", "dist", "build"]);

// Subtrees under a package's src/ that are consumed WITHOUT going through the
// package's dist/, so editing them never makes the dist stale:
// - i18n locale JSONs are loaded by apps through the `locales -> src/locales`
//   symlink (the dynamic import in dist resolves to that path), never bundled
//   into dist itself.
const SRC_EXCLUSIONS = {
  // - "locales": locale JSONs are loaded by apps through the
  //   `locales -> src/locales` symlink (the dynamic import in dist resolves to
  //   that path), never bundled into dist itself.
  // - "types/keys.generated.ts": regenerated by `generate:types`; type-only
  //   (erased at compile time) and `t()` takes a plain string, so it never
  //   affects the built bundle. Its freshness is covered by sync:check.
  "@plane/i18n": ["locales", "types/keys.generated.ts"],
};

function isExcluded(pkgName, relativePath) {
  const exclusions = SRC_EXCLUSIONS[pkgName] ?? [];
  return exclusions.some((excluded) => relativePath === excluded || relativePath.startsWith(`${excluded}/`));
}

function newestMtimeMs(dir, pkgName, relative = "") {
  let newest = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const rel = relative ? `${relative}/${entry.name}` : entry.name;
    if (isExcluded(pkgName, rel)) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      newest = Math.max(newest, newestMtimeMs(full, pkgName, rel));
    } else if (entry.isFile()) {
      newest = Math.max(newest, statSync(full).mtimeMs);
    }
  }
  return newest;
}

function oldestMtimeMs(dir) {
  let oldest = Number.POSITIVE_INFINITY;
  let found = false;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      const child = oldestMtimeMs(full);
      if (child.found) {
        found = true;
        oldest = Math.min(oldest, child.oldest);
      }
    } else if (entry.isFile()) {
      found = true;
      oldest = Math.min(oldest, statSync(full).mtimeMs);
    }
  }
  return { found, oldest };
}

const stale = [];

for (const name of readdirSync(PACKAGES_DIR)) {
  const pkgDir = join(PACKAGES_DIR, name);
  let pkgJson;
  try {
    pkgJson = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
  } catch {
    continue;
  }
  if (pkgJson.scripts?.build === undefined) continue;

  const srcDir = join(pkgDir, "src");
  const distDir = join(pkgDir, "dist");
  if (!existsSync(srcDir)) continue;

  if (!existsSync(distDir)) {
    stale.push(`${pkgJson.name ?? name} (dist/ missing — package was never built)`);
    continue;
  }
  const newestSrc = newestMtimeMs(srcDir, pkgJson.name ?? name);
  const { found, oldest } = oldestMtimeMs(distDir);
  if (!found || newestSrc > oldest) {
    stale.push(pkgJson.name ?? name);
  }
}

if (stale.length > 0) {
  console.error("[check-workspace-dists] STALE workspace package dist/ detected:");
  for (const name of stale) console.error(`  - ${name} (src/ is newer than dist/)`);
  console.error("Rebuild the dependencies first, e.g.:");
  console.error("  pnpm turbo run build --filter=web    # builds deps (^build) then web");
  console.error("or rebuild a single package: pnpm --filter=<package-name> build");
  process.exit(1);
}
